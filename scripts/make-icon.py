#!/usr/bin/env python3
"""Draw the soccer-ball icon (assets/soccer-ball.svg) and render .png/.ico/.icns from it."""
import math, os, subprocess, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(root, 'assets')
R = 120.0; C = 128.0  # ball radius and centre in a 256 box

def pt(r, deg):
    a = math.radians(deg); return (C + r * math.cos(a), C + r * math.sin(a))
def poly(points, **kw):
    attrs = ' '.join(f'{k.replace("_", "-")}="{v}"' for k, v in kw.items())
    return f'<polygon points="{" ".join(f"{x:.1f},{y:.1f}" for x, y in points)}" {attrs}/>'
def line(a, b):
    return f'<line x1="{a[0]:.1f}" y1="{a[1]:.1f}" x2="{b[0]:.1f}" y2="{b[1]:.1f}"/>'

rc = 0.27 * R                    # central pentagon
dirs = [-90 + 72 * i for i in range(5)]
central = [pt(rc, d) for d in dirs]
shapes, seams = [poly(central, fill='#111')], []
outer = []
for d in dirs:
    cx, cy = pt(0.86 * R, d)
    ro = 0.27 * R
    vs = []
    for k in range(5):          # vertex 0 points at the centre
        a = math.radians(d + 180 + 72 * k)
        vs.append((cx + ro * math.cos(a), cy + ro * math.sin(a)))
    outer.append(vs)
    shapes.append(poly(vs, fill='#111'))
for i, d in enumerate(dirs):
    seams.append(line(central[i], outer[i][0]))                      # centre vertex -> outer pentagon
    seams.append(line(outer[i][1], outer[(i + 1) % 5][4]))           # hexagon outer side
    for k in (2, 3):                                                 # out to the rim
        x, y = outer[i][k]; ang = math.degrees(math.atan2(y - C, x - C))
        seams.append(line(outer[i][k], pt(R * 1.1, ang)))

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
  <defs>
    <radialGradient id="shade" cx="38%" cy="32%" r="75%">
      <stop offset="0" stop-color="#ffffff"/><stop offset=".7" stop-color="#eef0f2"/><stop offset="1" stop-color="#b8bec6"/>
    </radialGradient>
    <clipPath id="ball"><circle cx="{C}" cy="{C}" r="{R}"/></clipPath>
  </defs>
  <circle cx="{C}" cy="{C}" r="{R}" fill="url(#shade)"/>
  <g clip-path="url(#ball)">
    <g stroke="#111" stroke-width="5" stroke-linecap="round">{''.join(seams)}</g>
    {''.join(shapes)}
  </g>
  <circle cx="{C}" cy="{C}" r="{R}" fill="none" stroke="#111" stroke-width="7"/>
</svg>
'''
os.makedirs(A, exist_ok=True)
open(os.path.join(A, 'soccer-ball.svg'), 'w').write(svg)
import json
open(os.path.join(root, 'src', 'gui', 'ball-svg.ts'), 'w').write('// Generated by scripts/make-icon.py from assets/soccer-ball.svg. Do not edit by hand.\nexport const BALL_SVG = ' + json.dumps(svg) + ';\n')

# Render with the preinstalled Chromium (Playwright), then build .ico/.icns with Pillow.
png = os.path.join(A, 'soccer-ball-1024.png')
html = os.path.join(A, '_render.html')
big = svg.replace('viewBox', 'width="1024" height="1024" viewBox', 1)
open(html, 'w').write('<html><body style="margin:0;background:transparent">' + big + '</body></html>')
js = f"""
const {{ chromium }} = require('playwright');
(async () => {{
  const b = await chromium.launch({{ executablePath: '/opt/pw-browsers/chromium' }});
  const p = await b.newPage({{ viewport: {{ width: 1024, height: 1024 }} }});
  await p.goto('file://{html}');
  await p.locator('svg').screenshot({{ path: '{png}', omitBackground: true }});
  await b.close();
}})();
"""
subprocess.run(['node', '-e', js], check=True, cwd=sys.argv[1] if len(sys.argv) > 1 else root)
os.remove(html)
from PIL import Image
im = Image.open(png).convert('RGBA')
im.save(os.path.join(A, 'soccer-ball.ico'), sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
im.save(os.path.join(A, 'soccer-ball.icns'))
im.resize((256, 256), Image.LANCZOS).save(os.path.join(A, 'soccer-ball-256.png'))
os.remove(png)
print('ok')
